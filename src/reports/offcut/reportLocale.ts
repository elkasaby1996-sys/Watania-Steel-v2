export type ReportText = keyof typeof arabicReportText;

export function createReportLocale(language: ReportLanguage = 'en') {
  const arabic = language === 'ar';
  const locale = arabic ? 'ar-QA-u-nu-latn' : 'en-GB';
  const t = (key: ReportText, values: Record<string, string | number> = {}) => (arabic ? arabicReportText[key] : key).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? `{${name}}`));
  const number = (value: number | null | undefined, digits = 3) => value == null ? t('Not available') : value.toLocaleString(locale, {minimumFractionDigits: digits, maximumFractionDigits: digits});
  const date = (value: string, short = false) => new Date(value.slice(0,10) + 'T12:00:00Z').toLocaleDateString(locale, { day:'2-digit', month:'short', ...(!short ? {year:'numeric' as const} : {}), calendar:'gregory', timeZone:'UTC' });
  const month = (value: string) => new Date(value + '-01T12:00:00Z').toLocaleDateString(locale, {month:'short',year:'numeric',calendar:'gregory',timeZone:'UTC'});
  const diameter = (value: string) => value === 'Other' ? t('Other / unspecified') : `${value} ${t('mm')}`;
  const pct = (value: number | null) => value == null ? t('N/A') : `${number(value,1)}%`;
  const preparedBy = (value: string) => /^cut-and-bend division$/i.test(value) ? t('Cut-and-Bend Division') : value;
  const issued = (report: {generatedAt?: string;generatedOn:string}) => {
    if (report.generatedAt) return date(report.generatedAt);
    const timestamp = Date.parse(report.generatedOn);
    return Number.isFinite(timestamp) ? date(new Date(timestamp).toISOString()) : report.generatedOn;
  };
  return {language,arabic,t,number,date,month,diameter,pct,preparedBy,issued};
}
